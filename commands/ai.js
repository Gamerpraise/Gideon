const fn = require('../functions')

module.exports = [
  {
    // Named .gideonai, not .gideon - "gideon" is already registered as an alias of .menu
    // (see commands/menu.js), so a plain .gideon always opened the menu instead of this.
    name: 'gideonai',
    aliases: ['ask'],
    desc: 'Ask Gideon AI anything - it checks the internet first, like asking Google: .gideonai <question>',
    category: 'ai',
    async run(sock, m, { args, text, config }) {
      let query = text || m.quoted?.text || ''
      if (/^ask\b/i.test(query)) query = query.replace(/^ask\s*/i, '') // .gideonai ask <question> still works
      if (!query) return m.reply(`Example: ${config.prefix}gideonai what is the capital of France`)
      await m.react('🔎')
      // Fetch a quick web summary first, then hand it to the model as context - closer to how
      // a search engine answers than a model guessing purely from what it was trained on.
      let context = ''
      try {
        const ddg = await fn.fetchJson(`https://api.duckduckgo.com/?q=${encodeURIComponent(query)}&format=json&no_html=1&skip_disambig=1`)
        const related = Array.isArray(ddg.RelatedTopics) ? ddg.RelatedTopics.map((t) => t.Text).filter(Boolean).slice(0, 3).join(' | ') : ''
        context = ddg.AbstractText || ddg.Answer || related || ''
      } catch {}
      const prompt = context ? `Web search context:\n${context}\n\nQuestion: ${query}\n\nAnswer accurately and concisely, using the web context above when it's relevant.` : query
      try {
        const data = await fn.fetchJson(
          `https://api.siputzx.my.id/api/ai/gpt3?prompt=${encodeURIComponent('You are Gideon, a WhatsApp assistant by Gpraise that fetches current information from the internet to answer accurately, like a search engine.')}&content=${encodeURIComponent(prompt)}`
        )
        const answer = data.data || data.result || data.response || data
        await m.react('✅')
        await m.reply(typeof answer === 'string' ? answer : JSON.stringify(answer))
      } catch {
        await m.react('❌')
        await m.reply('Gideon AI is busy. Try again later.')
      }
    }
  },
  {
    name: 'imagine',
    aliases: ['aiimage', 'draw'],
    desc: 'Generate an AI image, branded as Gideon (no pollinations.ai watermark)',
    category: 'ai',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .imagine a neon robot in Lagos')
      try {
        // nologo=true strips pollinations.ai's own watermark; the caption below is Gideon's
        // branding in its place, since the image itself has no room to put a logo into.
        const seed = Date.now() % 1000000
        const url = `https://image.pollinations.ai/prompt/${encodeURIComponent(text)}?nologo=true&seed=${seed}`
        await sock.sendMessage(m.chat, { image: { url }, caption: `${text}\n\n🤖 Generated by Gideon` })
      } catch {
        await m.reply('Image generation failed.')
      }
    }
  },
  {
    name: 'lyrics',
    aliases: ['lyric'],
    desc: 'Find song lyrics',
    category: 'search',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .lyrics faded')
      try {
        const data = await fn.fetchJson(`https://api.lyrics.ovh/v1/${encodeURIComponent(text)}/${encodeURIComponent(text)}`)
        if (!data.lyrics) return m.reply('Lyrics not found.')
        await m.reply(data.lyrics.slice(0, 4000))
      } catch {
        await m.reply('Lyrics not found.')
      }
    }
  },
  {
    name: 'wiki',
    aliases: ['wikipedia'],
    desc: 'Search Wikipedia',
    category: 'search',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .wiki Nigeria')
      try {
        const data = await fn.fetchJson(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(text)}`)
        await m.reply(`*${data.title}*\n${data.extract}`)
      } catch {
        await m.reply('No Wikipedia result.')
      }
    }
  },
  {
    name: 'define',
    aliases: ['dictionary', 'dict'],
    desc: 'Define a word',
    category: 'search',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .define bot')
      try {
        const data = await fn.fetchJson(`https://api.dictionaryapi.dev/api/v2/entries/en/${encodeURIComponent(text)}`)
        const meaning = data[0]?.meanings?.[0]?.definitions?.[0]?.definition
        await m.reply(meaning || 'No definition found.')
      } catch {
        await m.reply('No definition found.')
      }
    }
  },
  {
    name: 'npm',
    aliases: ['npmjs'],
    desc: 'Search npm packages',
    category: 'search',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .npm baileys')
      try {
        const data = await fn.fetchJson(`https://registry.npmjs.org/${encodeURIComponent(text)}`)
        await m.reply(`*${data.name}*\n${data.description || '-'}\nLatest: ${data['dist-tags']?.latest}\n${data.homepage || ''}`)
      } catch {
        await m.reply('Package not found.')
      }
    }
  },
  {
    name: 'github',
    aliases: ['ghuser'],
    desc: 'Get GitHub user info',
    category: 'search',
    async run(sock, m, { text }) {
      if (!text) return m.reply('Example: .github torvalds')
      try {
        const data = await fn.fetchJson(`https://api.github.com/users/${encodeURIComponent(text)}`)
        await sock.sendMessage(m.chat, {
          image: { url: data.avatar_url },
          caption: `*${data.login}*\n${data.bio || '-'}\nRepos: ${data.public_repos}\nFollowers: ${data.followers}\n${data.html_url}`
        })
      } catch {
        await m.reply('User not found.')
      }
    }
  }
]
